def classify_hole_cards(cards: Sequence[PokerEvalCard]) -> Optional[str]:
    """Return compact poker notation such as ``AKs``, ``AQo`` or ``TT``."""

    if len(cards) != 2 or any(card is None for card in cards):
        return None
    if any(not hasattr(card, "rank") or not hasattr(card, "suit") for card in cards):
        return None

    left, right = cards
    left_rank = int(left.rank)
    right_rank = int(right.rank)
    if left_rank not in RANK_LABELS or right_rank not in RANK_LABELS:
        return None

    ranks = sorted((left_rank, right_rank), reverse=True)
    high, low = ranks
    high_label = RANK_LABELS[high]
    low_label = RANK_LABELS[low]
    if high == low:
        return f"{high_label}{low_label}"
    suffix = "s" if int(left.suit) == int(right.suit) else "o"
    return f"{high_label}{low_label}{suffix}"


def get_hand_action(position: str, hand: str) -> RangeAction:
    """Return range action for ``hand`` at ``position``, defaulting to fold."""

    normalized = normalize_position(position)
    if normalized is None:
        return RangeAction()
    return RANGES[normalized].get(hand, RangeAction())


def is_hand_in_range(position: str, hand: str) -> bool:
    return get_hand_action(position, hand).playable_frequency > 0


def get_range_percentage(position: str) -> float:
    """Return approximate percentage of all 1326 combos played by a range."""

    normalized = normalize_position(position)
    if normalized is None:
        return 0.0

    combo_count = 0.0
    for hand, action in RANGES[normalized].items():
        combo_count += _hand_combo_count(hand) * (action.playable_frequency / 100.0)
    return (combo_count / 1326.0) * 100.0


def normalize_position(position: object) -> Optional[Position]:
    text = str(position or "").strip().upper()
    aliases = {
        "BUTTON": "BTN",
        "DEALER": "BTN",
        "CUTOFF": "CO",
        "SMALL_BLIND": "SB",
        "BIG_BLIND": "BB",
    }
    text = aliases.get(text, text)
    return text if text in POSITIONS else None


def _hand_combo_count(hand: str) -> int:
    if len(hand) == 2:
        return 6
    if hand.endswith("s"):
        return 4
    return 12


