@dataclass(frozen=True)
class RangeAction:
    """Opening/defense frequencies for a starting hand."""

    raise_frequency: int = 0
    call_frequency: int = 0
    fold_frequency: int = 100

    @property
    def playable_frequency(self) -> int:
        return self.raise_frequency + self.call_frequency


def _action(raise_frequency: int, call_frequency: int = 0, fold_frequency: int = 0) -> RangeAction:
    return RangeAction(
        raise_frequency=raise_frequency,
        call_frequency=call_frequency,
        fold_frequency=fold_frequency,
    )


